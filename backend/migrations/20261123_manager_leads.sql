-- Additive manager Leads lifecycle. This migration is intentionally not applied by the app.
-- Lead and activity history use RESTRICT/NO ACTION deletes so records cannot disappear
-- through normal parent deletion. Assignment history remains append-only as well.

CREATE TABLE IF NOT EXISTS leads (
    id INT NOT NULL AUTO_INCREMENT,
    customer_name VARCHAR(100) NOT NULL,
    customer_phone VARCHAR(20) NOT NULL,
    address VARCHAR(500) NOT NULL,
    source VARCHAR(20) NULL,
    referred_by VARCHAR(100) NULL,
    referrer_phone VARCHAR(20) NULL,
    channel_partner VARCHAR(160) NULL,
    commission VARCHAR(160) NULL,
    department_id INT NOT NULL,
    current_department_id INT NULL,
    lead_date DATE NOT NULL,
    initial_remark VARCHAR(1000) NOT NULL,
    latest_remark VARCHAR(1000) NOT NULL,
    next_follow_up_date DATE NULL,
    status VARCHAR(24) NOT NULL,
    created_by_user_id INT NOT NULL,
    assigned_to_user_id INT NULL,
    assigned_department_id INT NULL,
    needs_creator_review TINYINT(1) NOT NULL DEFAULT 0,
    review_kind VARCHAR(32) NULL,
    finalized_at DATETIME NULL,
    final_confirmed_at DATETIME NULL,
    final_confirmed_by_user_id INT NULL,
    work_started_at DATETIME NULL,
    work_review_pending TINYINT(1) NOT NULL DEFAULT 0,
    work_review_submitted_at DATETIME NULL,
    cancelled_at DATETIME NULL,
    completed_at DATETIME NULL,
    completed_by_user_id INT NULL,
    version INT NOT NULL DEFAULT 1,
    create_request_key VARCHAR(64) NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_leads_create_request (created_by_user_id, create_request_key),
    KEY idx_leads_status_followup (status, next_follow_up_date),
    KEY idx_leads_assignee_status (assigned_to_user_id, status),
    KEY idx_leads_creator_review (created_by_user_id, needs_creator_review, status),
    KEY idx_leads_created_at (created_at),
    CONSTRAINT fk_leads_department FOREIGN KEY (department_id) REFERENCES departments (id) ON DELETE RESTRICT,
    CONSTRAINT fk_leads_current_department FOREIGN KEY (current_department_id) REFERENCES departments (id) ON DELETE RESTRICT,
    CONSTRAINT fk_leads_assigned_department FOREIGN KEY (assigned_department_id) REFERENCES departments (id) ON DELETE RESTRICT,
    CONSTRAINT fk_leads_creator FOREIGN KEY (created_by_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_leads_assignee FOREIGN KEY (assigned_to_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_leads_final_confirmer FOREIGN KEY (final_confirmed_by_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_leads_completer FOREIGN KEY (completed_by_user_id) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS lead_assignments (
    id INT NOT NULL AUTO_INCREMENT,
    lead_id INT NOT NULL,
    user_id INT NOT NULL,
    department_id INT NOT NULL,
    assignment_type VARCHAR(16) NOT NULL,
    assigned_by_user_id INT NOT NULL,
    instruction VARCHAR(1000) NULL,
    started_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at DATETIME NULL,
    ended_reason VARCHAR(1000) NULL,
    PRIMARY KEY (id),
    KEY idx_lead_assignments_current (lead_id, ended_at, id),
    KEY idx_lead_assignments_user (user_id, ended_at),
    CONSTRAINT fk_lead_assignments_lead FOREIGN KEY (lead_id) REFERENCES leads (id) ON DELETE RESTRICT,
    CONSTRAINT fk_lead_assignments_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_lead_assignments_department FOREIGN KEY (department_id) REFERENCES departments (id) ON DELETE RESTRICT,
    CONSTRAINT fk_lead_assignments_actor FOREIGN KEY (assigned_by_user_id) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS lead_activities (
    id INT NOT NULL AUTO_INCREMENT,
    lead_id INT NOT NULL,
    actor_user_id INT NOT NULL,
    event_type VARCHAR(40) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    metadata JSON NULL,
    request_key VARCHAR(64) NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_lead_activities_request (request_key),
    KEY idx_lead_activities_timeline (lead_id, created_at, id),
    CONSTRAINT fk_lead_activities_lead FOREIGN KEY (lead_id) REFERENCES leads (id) ON DELETE RESTRICT,
    CONSTRAINT fk_lead_activities_actor FOREIGN KEY (actor_user_id) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
